"""Render exact-wheel hashes in native Windows conda shortcutminer."""
import argparse
import hashlib
import json
from pathlib import Path
import platform
import importlib.metadata
import sys
from urllib.parse import unquote, urlsplit
from packaging.tags import sys_tags
from packaging.utils import parse_wheel_filename


def canonical(name):
    return name.lower().replace("_", "-").replace(".", "-")


def write_standalone_requirements(path, formal, tools, direct_names):
    packages = {p["name"]: p for p in formal + tools}
    groups = [("Scientific direct dependencies", list(direct_names)),
              ("GPU runtime: official Windows CUDA 12.8 wheels", ["torch", "torchvision"]),
              ("Build tools", ["pip", "setuptools", "wheel"])]
    first = {canonical(name) for _, names in groups for name in names}
    groups.append(("Complete transitive dependencies", sorted(set(packages) - first)))
    lines = ["# Windows AMD64; conda shortcutminer; Python 3.11.16.",
             "# Standalone file: all exact versions and Windows wheel SHA-256 hashes.",
             "# CMD or PowerShell: python -m pip install --no-deps -r requirements.txt",
             "--index-url https://pypi.org/simple",
             "--extra-index-url https://download.pytorch.org/whl/cu128",
             "--only-binary=:all:", "--require-hashes", ""]
    for title, names in groups:
        lines.append("# " + title)
        for name in names:
            p = packages[canonical(name)]
            lines.append(f"{name}=={p['version']} --hash=sha256:{p['sha256']}")
        lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")


def render(report_path, lock_path, expected, target="windows"):
    report = json.loads(report_path.read_text(encoding="utf-8"))
    packages = []
    compatible_tags = set(sys_tags())
    for item in report["install"]:
        metadata = item["metadata"]
        url = item["download_info"]["url"]
        wheel = unquote(urlsplit(url).path.rsplit("/", 1)[-1])
        if not wheel.endswith(".whl") or not url.startswith("https://"):
            raise RuntimeError("Lock requires an HTTPS wheel: " + metadata["name"])
        if not (parse_wheel_filename(wheel)[3] & compatible_tags):
            raise RuntimeError("STOP: incompatible Windows wheel: " + wheel)
        digest = item["download_info"]["archive_info"]["hashes"]["sha256"]
        packages.append({"name": canonical(metadata["name"]), "version": metadata["version"],
                         "wheel": wheel, "url": url, "sha256": digest})
    versions = {p["name"]: p["version"] for p in packages}
    for name, version in expected.items():
        actual = versions.get(canonical(name))
        if actual != version:
            raise RuntimeError(f"STOP: pinned dependency conflict: {name} expected {version}, got {actual}")
    for name in ("torch", "torchvision"):
        if name in versions:
            value = next(p for p in packages if p["name"] == name)
            if not value["version"].endswith("+cu128") or not urlsplit(value["url"]).hostname.endswith("pytorch.org"):
                raise RuntimeError("STOP: GPU wheel is not official cu128")
    lines = [f"# Generated by pip {importlib.metadata.version('pip')} in {target}, Python 3.11.16.",
             "# Exact Windows wheel URLs; install with --no-deps.",
             "--only-binary=:all:", "--require-hashes", ""]
    for p in sorted(packages, key=lambda x: x["name"]):
        lines += [f"# {p['name']}=={p['version']} | {p['wheel']}",
                  f"{p['name']} @ {p['url']} --hash=sha256:{p['sha256']}", ""]
    lock_path.write_text("\n".join(lines), encoding="utf-8")
    return sorted(packages, key=lambda x: x["name"])


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--target", choices=["windows"], default="windows")
    parser.add_argument("--reports", type=Path, required=True)
    parser.add_argument("--repository", type=Path, required=True)
    args = parser.parse_args()
    if platform.python_version() != "3.11.16":
        raise RuntimeError("Lock generation requires Python 3.11.16")
    if sys.platform != "win32" or platform.machine().lower() not in {"amd64", "x86_64"} or Path(sys.prefix).name != "shortcutminer":
        raise RuntimeError("Windows lock requires native conda shortcutminer AMD64")
    formal_name, tools_name = "formal-win64-py311.lock", "build-tools-win64.lock"
    tool_pins = {"pip": "26.2.1", "setuptools": "83.0.0", "wheel": "0.47.0"}
    expected = {}
    for line in (args.repository / "requirements/core.in").read_text(encoding="utf-8").splitlines():
        if "==" in line and not line.startswith("#"):
            name, version = line.strip().split("==")
            expected[name] = version
    direct_names = list(expected)
    expected.update(torch="2.9.1+cu128", torchvision="0.24.1+cu128")
    formal = render(args.reports / "resolution.json", args.repository / "requirements" / formal_name, expected, args.target)
    tools = render(args.reports / "build-tools-resolution.json", args.repository / "requirements" / tools_name, tool_pins, args.target)
    merged = {p["name"]: p["version"] for p in formal}
    for p in tools:
        if p["name"] in merged and merged[p["name"]] != p["version"]:
            raise RuntimeError("STOP: build/runtime dependency conflict: " + p["name"])
    write_standalone_requirements(args.repository / "requirements.txt", formal, tools, direct_names)
    (args.reports / "locked-packages.json").write_text(json.dumps({"formal": formal, "build_tools": tools}, indent=2) + "\n")
    print(json.dumps({"formal_packages": len(formal), "build_tool_packages": len(tools)}))


if __name__ == "__main__":
    main()
